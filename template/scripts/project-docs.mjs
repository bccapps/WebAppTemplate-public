/**
 * Root agent documents of a project.
 *   node scripts/project-docs.mjs ensure [<project-root>]
 *
 * - CLAUDE.md: a REAL file = @imports of the library rules + marker + project notes.
 *     @front/.libs/apptemplate/CLAUDE.md
 *     @front/.libs/vx-private/CLAUDE.private.md      (only when vx-private is mounted)
 *     <!-- project-specific notes below -->
 *   A legacy symlink is replaced; an existing real file keeps everything below the marker
 *   (or its whole content, for a legacy real file without marker).
 * - AGENTS.md: GENERATED (imports inlined + project notes), git-ignored, never edited by hand.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const MARKER = '<!-- project-specific notes below -->';
export const TEMPLATE_IMPORT = '@front/.libs/apptemplate/CLAUDE.md';
export const PRIVATE_IMPORT = '@front/.libs/vx-private/CLAUDE.private.md';
const AGENTS_BANNER = '<!-- GENERATED by scripts/update_common.sh from CLAUDE.md and its @imports — do not edit, edit CLAUDE.md -->';

const isLink = (p) => {
  try {
    return lstatSync(p).isSymbolicLink();
  } catch {
    return false;
  }
};

/** Import lines for a project. */
export function importLines(root) {
  const lines = [TEMPLATE_IMPORT];
  if (existsSync(path.join(root, 'front', '.libs', 'vx-private'))) lines.push(PRIVATE_IMPORT);
  return lines;
}

/** New CLAUDE.md content from the previous content (null = none / symlink). Pure. */
export function renderClaudeMd(previous, imports) {
  let notes = '';
  if (previous !== null && previous.includes(MARKER)) notes = previous.slice(previous.indexOf(MARKER) + MARKER.length).replace(/^\n/, '');
  else if (previous !== null && !/^@/m.test(previous)) notes = previous.trim() ? `${previous.replace(/\s+$/, '')}\n` : '';
  return `${imports.join('\n')}\n${MARKER}\n${notes}`;
}

/** AGENTS.md content: each @import line inlined, the rest kept. Pure over a reader. */
export function renderAgentsMd(claudeMd, readImport) {
  const body = claudeMd.split('\n').map((line) => {
    const m = line.match(/^@(\S+)\s*$/);
    if (!m) return line;
    const text = readImport(m[1]);
    return text === null ? `<!-- missing import: ${m[1]} -->` : text.replace(/\s+$/, '');
  });
  return `${AGENTS_BANNER}\n${body.join('\n')}`;
}

function git(root, args) {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    return null;
  }
}

/** Lines every project's `.gitignore` must hold (appended once when missing; the rest of the file is never touched). */
export const REQUIRED_GITIGNORE = [
  { line: '/AGENTS.md', present: /^\/AGENTS\.md\s*$/m, comment: 'Generated for agents that do not follow @imports (scripts/update_common.sh)' },
  { line: 'logs/', present: /^\/?(?:\*\*\/)?logs\/?\s*$/m, comment: 'Logs (back-<day>.log, validation-<day>.jsonl): never committed' },
  { line: '.validation-cache/', present: /^\/?\.validation-cache\/?\s*$/m, comment: 'Local copies and state of scripts/validation-report.mjs' },
];

/** `.gitignore` content with the missing required lines appended (pure). */
export function withRequiredGitignore(text) {
  let out = text;
  for (const { line, present, comment } of REQUIRED_GITIGNORE) {
    if (!present.test(out)) out = `${out.replace(/\n*$/, '\n')}\n# ${comment}\n${line}\n`;
  }
  return out.replace(/^\n+/, '');
}

function ensureGitignore(root) {
  const file = path.join(root, '.gitignore');
  const text = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const next = withRequiredGitignore(text);
  if (next !== text) writeFileSync(file, next);
}

export function ensure(root) {
  const claude = path.join(root, 'CLAUDE.md');
  const agents = path.join(root, 'AGENTS.md');
  let previous = null;
  if (existsSync(claude) && !isLink(claude)) previous = readFileSync(claude, 'utf8');
  if (isLink(claude)) rmSync(claude);
  const content = renderClaudeMd(previous, importLines(root));
  writeFileSync(claude, content);

  if (isLink(agents)) rmSync(agents);
  if (git(root, ['ls-files', '--error-unmatch', 'AGENTS.md']) !== null) git(root, ['rm', '--cached', '-q', 'AGENTS.md']);
  ensureGitignore(root);
  const read = (rel) => {
    const file = path.join(root, rel);
    return existsSync(file) ? readFileSync(file, 'utf8') : null;
  };
  writeFileSync(agents, renderAgentsMd(content, read));
  return { claudeChanged: previous !== content };
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [command, rootArg] = process.argv.slice(2);
  if (command !== 'ensure') {
    console.error('usage: project-docs.mjs ensure [<project-root>]');
    process.exitCode = 2;
  } else {
    const root = path.resolve(rootArg ?? process.cwd());
    const { claudeChanged } = ensure(root);
    console.log(`[project-docs] CLAUDE.md ${claudeChanged ? 'updated' : 'unchanged'}, AGENTS.md regenerated`);
  }
}
