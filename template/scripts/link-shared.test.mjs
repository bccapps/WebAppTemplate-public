import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readlinkSync, lstatSync, symlinkSync, existsSync, rmSync } from 'fs';
import { tmpdir } from 'os';
import path from 'path';
import { linkShared, renderPluginsFile } from './link-shared.mjs';

const quiet = async (fn) => {
  const { log, warn, error } = console;
  console.log = console.warn = console.error = () => {};
  try {
    return await fn();
  } finally {
    Object.assign(console, { log, warn, error });
  }
};

function project(shared, dirs) {
  const root = mkdtempSync(path.join(tmpdir(), 'ls-'));
  for (const d of dirs) mkdirSync(path.join(root, d), { recursive: true });
  writeFileSync(path.join(root, 'shared-modules.json'), JSON.stringify(shared));
  return root;
}

test('renderPluginsFile: with and without common', () => {
  assert.equal(
    renderPluginsFile(['common', 'user', 'voice'], new Set(['user', 'voice'])),
    "// AUTO-GENERATED by link-shared.mjs — do not edit.\n" +
      "import type { NestModulePlugin } from './common/plugins/NestModulePlugin';\n" +
      "import { plugin as p0 } from './user/plugin';\n" +
      "import { plugin as p1 } from './voice/plugin';\n" +
      'export const sharedPlugins: NestModulePlugin[] = [p0, p1];\n',
  );
  assert.match(renderPluginsFile(['common'], new Set()), /NestModulePlugin\[\] = \[\];/);
  assert.match(renderPluginsFile(['database'], new Set()), /export const sharedPlugins = \[\] as const;/);
});

test('back: relative symlinks, prunes orphans, keeps real dirs, writes plugins file; idempotent', async () => {
  const root = project({ nestcommon: ['common', 'user', 'ghost'] }, [
    'back/.libs/vx-public/nest/common', 'back/.libs/vx-private/nest/user', 'back/src/modules_shared/own',
  ]);
  writeFileSync(path.join(root, 'back/.libs/vx-private/nest/user/plugin.ts'), 'export const plugin = {};');
  const back = path.join(root, 'back');
  const mods = path.join(back, 'src/modules_shared');
  symlinkSync('../../.libs/old', path.join(mods, 'stale'));
  await quiet(() => linkShared('back', back));
  assert.equal(readlinkSync(path.join(mods, 'common')), path.join('..', '..', '.libs', 'vx-public', 'nest', 'common'));
  assert.equal(existsSync(path.join(mods, 'ghost')), false);
  assert.equal(existsSync(path.join(mods, 'stale')) || (() => { try { lstatSync(path.join(mods, 'stale')); return true; } catch { return false; } })(), false);
  assert.ok(lstatSync(path.join(mods, 'own')).isDirectory());
  const generated = readFileSync(path.join(mods, 'plugins.generated.ts'), 'utf8');
  assert.match(generated, /import \{ plugin as p0 \} from '.\/user\/plugin';/);
  await quiet(() => linkShared('back', back)); // second run keeps the generated file
  assert.equal(readFileSync(path.join(mods, 'plugins.generated.ts'), 'utf8'), generated);
  rmSync(root, { recursive: true });
});

test('front: no plugins file; missing shared-modules.json links and prunes nothing', async () => {
  const root = project({ reactcommon: ['common'] }, ['front/.libs/reactcommon/common']);
  const front = path.join(root, 'front');
  await quiet(() => linkShared('front', front));
  assert.equal(existsSync(path.join(front, 'src/modules_shared/plugins.generated.ts')), false);
  assert.ok(lstatSync(path.join(front, 'src/modules_shared/common')).isSymbolicLink());
  rmSync(path.join(root, 'shared-modules.json'));
  symlinkSync('x', path.join(front, 'src/modules_shared/keepme'));
  await quiet(() => linkShared('front', front));
  assert.ok(lstatSync(path.join(front, 'src/modules_shared/keepme')).isSymbolicLink());
  rmSync(root, { recursive: true });
});
