/**
 * Materializes the shared library modules used by this app into
 * `src/modules_shared/` as **gitignored symlinks**. The compilers (Nest, Vite)
 * only see files physically under `src/`, so the shared modules must appear there.
 *
 * Usage — run from the STACK directory (back/ or front/):
 *     node .libs/apptemplate/scripts/link-shared.mjs <back|front>
 *
 * The list of modules comes SOLELY from `<project-root>/shared-modules.json`
 * (key "nestcommon" for back, "reactcommon" for front; a plain array is also
 * accepted). There is NO fallback: a missing/invalid file is a configuration
 * error and nothing is linked or pruned.
 *
 * Each module is resolved through scripts/lib-roots.mjs (vx-public, then
 * vx-private, then the legacy .libs/nestcommon | .libs/reactcommon checkout).
 *
 * The script is the single source of truth for `modules_shared`: it links exactly
 * the listed modules and PRUNES every other symlink. Real files/directories are
 * never touched, so app-owned modules physically present there stay intact.
 *
 * Back only: also writes `src/modules_shared/plugins.generated.ts`, the list of
 * the `plugin` exports of linked modules that provide a `plugin.ts`, and the modules to import
 * (`sharedPluginModules`: ordered, factories fed by `src/config/pluginOptions.ts` when the app has it).
 *
 * Run automatically via postinstall / prebuild / prestart(:dev) / predev.
 */

import { mkdir, lstat, readlink, readdir, rm, symlink, writeFile } from 'fs/promises';
import { existsSync, readFileSync, realpathSync } from 'fs';
import path from 'path';
import process from 'process';
import { fileURLToPath } from 'url';
import { libRoots, readSharedModules, resolveModule } from './lib-roots.mjs';

/** Create (or refresh) a single module symlink, idempotently. */
async function linkModule(modulesDir, moduleName, absTarget) {
  const linkPath = path.join(modulesDir, moduleName);
  const target = path.relative(modulesDir, absTarget);

  try {
    const stats = await lstat(linkPath);
    if (stats.isSymbolicLink() && (await readlink(linkPath)) === target) return;
    await rm(linkPath, { recursive: true, force: true });
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }

  await symlink(target, linkPath);
}

/**
 * Remove any symlink under modulesDir not in the allowlist. Real files/dirs are
 * never touched (app-owned physical modules stay), only symlinks are pruned.
 */
async function pruneStaleLinks(modulesDir, keep) {
  let entries;
  try {
    entries = await readdir(modulesDir);
  } catch {
    return 0;
  }
  let pruned = 0;
  for (const name of entries) {
    if (keep.has(name)) continue;
    const linkPath = path.join(modulesDir, name);
    let stats;
    try {
      stats = await lstat(linkPath);
    } catch {
      continue;
    }
    if (!stats.isSymbolicLink()) continue;
    await rm(linkPath, { force: true });
    pruned += 1;
    console.log(`  Pruned ${name}`);
  }
  return pruned;
}

/**
 * Source text of src/modules_shared/plugins.generated.ts (back only).
 * `sharedPlugins` lists the plugins in shared-modules.json order; `sharedPluginModules` is what AppModule imports:
 * the modules of every plugin sorted by `order`, factories called with `pluginOptions[<plugin id>]`.
 * @param {string[]} linkedModules
 * @param {Set<string>} withPlugin
 * @param {{ hasPluginOptions?: boolean }} [opts] hasPluginOptions: the app has `src/config/pluginOptions.ts`
 */
export function renderPluginsFile(linkedModules, withPlugin, opts = {}) {
  const banner = '// AUTO-GENERATED by link-shared.mjs — do not edit.\n';
  if (!linkedModules.includes('common')) return `${banner}export const sharedPlugins = [] as const;\nexport const sharedPluginModules = [] as const;\n`;
  const withPlugins = linkedModules.filter((m) => withPlugin.has(m));
  const imports = withPlugins.map((m, i) => `import { plugin as p${i} } from './${m}/plugin';`);
  const options = opts.hasPluginOptions ? "import { pluginOptions } from '../config/pluginOptions';" : null;
  return [
    banner.trimEnd(),
    "import type { NestModulePlugin } from './common/plugins/NestModulePlugin';",
    "import { resolvePluginModules } from './common/plugins/resolvePlugins';",
    ...(options ? [options] : []),
    ...imports,
    `export const sharedPlugins: NestModulePlugin<never>[] = [${withPlugins.map((_, i) => `p${i}`).join(', ')}];`,
    `export const sharedPluginModules = resolvePluginModules(sharedPlugins${opts.hasPluginOptions ? ', pluginOptions' : ''});`,
    '',
  ].join('\n');
}

async function writeIfChanged(file, content) {
  let current = null;
  try {
    current = readFileSync(file, 'utf8');
  } catch {
    // missing file: write it
  }
  if (current !== content) await writeFile(file, content);
}

/**
 * Link the shared modules of one stack.
 * @param {'back'|'front'} stack
 * @param {string} stackDir absolute path of <project>/<stack>
 */
export async function linkShared(stack, stackDir) {
  const projectRoot = path.resolve(stackDir, '..');
  const modulesDir = path.join(stackDir, 'src', 'modules_shared');
  const modules = readSharedModules(projectRoot, stack, (reason) =>
    console.error(`[link-shared] ✖ ${reason} — aucun module lié.`),
  );
  if (!modules) return; // misconfiguration already reported; never link/prune blindly.

  const roots = libRoots(stack, stackDir);
  if (!roots.length) {
    // Non-fatal so `npm install` (postinstall) never aborts before the libs are checked out.
    console.warn(
      `[link-shared] ⚠ Aucune source trouvée (.libs/vx-public, .libs/vx-private, .libs/${stack === 'back' ? 'nestcommon' : 'reactcommon'}).`,
    );
    return;
  }

  await mkdir(modulesDir, { recursive: true });
  const linked = [];
  const withPlugin = new Set();
  for (const name of modules) {
    const found = resolveModule(stack, stackDir, name);
    if (!found) {
      console.warn(`[link-shared] ⚠ module introuvable dans les libs: ${name}`);
      continue;
    }
    await linkModule(modulesDir, name, found.dir);
    linked.push(name);
    if (stack === 'back' && (await lstat(path.join(found.dir, 'plugin.ts')).catch(() => null))) {
      withPlugin.add(name);
    }
  }

  if (stack === 'back') {
    const hasPluginOptions = existsSync(path.join(stackDir, 'src', 'config', 'pluginOptions.ts'));
    await writeIfChanged(
      path.join(modulesDir, 'plugins.generated.ts'),
      renderPluginsFile(linked, withPlugin, { hasPluginOptions }),
    );
  }
  const pruned = await pruneStaleLinks(modulesDir, new Set(modules));
  console.log(
    `[link-shared] ${linked.length}/${modules.length} modules liés` +
      `${pruned ? `, ${pruned} orphelin(s) purgé(s)` : ''} depuis ${roots.map((r) => r.name).join(' + ')}.`,
  );
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const stack = process.argv[2] || path.basename(process.cwd());
  if (!['back', 'front'].includes(stack)) {
    console.error('[link-shared] ✖ usage: link-shared.mjs <back|front> (run from the stack directory)');
    process.exitCode = 1;
  } else {
    await linkShared(stack, process.cwd());
  }
}
