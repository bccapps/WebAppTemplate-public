import { Module } from '@nestjs/common';
import { ScheduleModule } from '@nestjs/schedule';
import { DatabaseModule } from 'src/modules_shared/database';
import { CommonModule } from 'src/modules_shared/common/CommonModule';
import { AuthCoreModule } from 'src/modules_shared/common/auth/AuthCoreModule';
import { sharedPlugins } from 'src/modules_shared/plugins.generated';
import AppDataSource, { dbContext } from 'src/config/Datasource';

// Linked shared modules exposing a `plugin.ts` (generated by link-shared.mjs). At most one of them
// may provide authentication (`user` does; without it the app runs anonymously with ADMIN_TOKEN).
const authPlugins = sharedPlugins.filter((p) => p.auth);
if (authPlugins.length > 1) {
  throw new Error(`Several auth plugins linked: ${authPlugins.map((p) => p.id).join(', ')}`);
}

// Shared modules WITHOUT a plugin.ts (e.g. voice) must still be added by hand to `imports`,
// next to any app-specific module under src/modules/<feature>.
@Module({
  imports: [
    ScheduleModule.forRoot(),
    DatabaseModule.forRoot({ context: dbContext, mainDataSource: AppDataSource }),
    CommonModule,
    AuthCoreModule.forRoot(authPlugins[0]?.auth),
    ...sharedPlugins.flatMap((p) => (p.module ? [p.module] : [])),
  ],
  controllers: [],
  providers: [],
})
export class AppModule {}
