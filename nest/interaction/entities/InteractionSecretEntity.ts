import { Column, CreateDateColumn, Entity, PrimaryColumn } from 'typeorm';
import { timestampColumnType } from '../../common/utils/dbEngine';

/**
 * Default secret store (04 §6, §13): `ciphertext` = `CryptService.encryptForStorage(value, 'interaction:secret:<id>')`
 * (one namespace per row, so a ciphertext copied onto another row does not decrypt). Never exposed.
 */
@Entity({ name: 'interaction_secret' })
export class InteractionSecretEntity {
  /** Generated by the app before encryption (it is part of the namespace). */
  @PrimaryColumn({ type: 'uuid' })
  id: string;

  @Column({ type: 'varchar', length: 24 })
  kind: string;

  @Column({ name: 'owner_user_id', type: 'integer', nullable: true, default: null })
  ownerUserId: number | null;

  @Column({ type: 'text' })
  ciphertext: string;

  @CreateDateColumn({ name: 'created_at', type: timestampColumnType() })
  createdAt: Date;

  @Column({ name: 'rotated_at', type: timestampColumnType(), nullable: true, default: null })
  rotatedAt: Date | null;

  @Column({ name: 'last_used_at', type: timestampColumnType(), nullable: true, default: null })
  lastUsedAt: Date | null;
}
